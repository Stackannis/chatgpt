/* Pompom Parade - build the YouTube Playables package (Node, no dependencies).
 *   node tools/package_playables.js [--no-sdk] [--out dist/playables]
 * Copies index.html, css/ and js/ to dist/playables/ WITHOUT js/debug/ (and of course without review/, tests/,
 * tools/, docs/), sets PP.BUILD = 'playables', replaces the debug loader by a stub and inserts the Playables
 * SDK <script> tag (skip with --no-sdk for offline checks). In that build URL parameters are ignored and
 * window.__game does not exist. Fails if any debug hook is still referenced by the shipped files. */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const args = process.argv.slice(2);
const noSdk = args.indexOf('--no-sdk') >= 0;
const outArg = args.indexOf('--out') >= 0 ? args[args.indexOf('--out') + 1] : 'dist/playables';
const out = path.resolve(root, outArg);
const SDK_TAG = '<script src="https://www.youtube.com/game_api/v1"></script>';
const SKIP_DIRS = [path.join('js', 'debug')];

function rmrf(p) { if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); }
function copyDir(rel) {
  const src = path.join(root, rel), dst = path.join(out, rel);
  if (SKIP_DIRS.indexOf(rel) >= 0) return;
  fs.mkdirSync(dst, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const r = path.join(rel, name), st = fs.statSync(path.join(root, r));
    if (st.isDirectory()) copyDir(r);
    else if (/\.(js|css|html)$/.test(name)) fs.copyFileSync(path.join(root, r), path.join(out, r));
  }
}
function walk(dir, list) {
  for (const name of fs.readdirSync(dir)) { const p = path.join(dir, name); if (fs.statSync(p).isDirectory()) walk(p, list); else list.push(p); }
  return list;
}

if (!out.startsWith(path.join(root, 'dist'))) { console.error('refusing to write outside dist/: ' + out); process.exit(2); }
rmrf(out);
fs.mkdirSync(out, { recursive: true });
copyDir('css');
copyDir('js');

// build flag + debug loader stub
fs.writeFileSync(path.join(out, 'js', 'build_flags.js'),
  "/* Pompom Parade - build flags (YouTube Playables package, generated by tools/package_playables.js) */\nwindow.PP.BUILD = 'playables';\n");
fs.writeFileSync(path.join(out, 'js', 'core', 'debug_loader.js'),
  "/* Pompom Parade - Playables package: there is no debug code in this build. */\n(function () {\n  'use strict';\n  var PP = window.PP;\n  PP.debugAllowed = function () { return false; };\n  PP.loadDebug = function (cb) { cb(); };\n})();\n");

// index.html: SDK tag in the first script slot
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
if (html.indexOf('<!-- PLAYABLES SDK HERE -->') < 0) { console.error('index.html: SDK placeholder not found'); process.exit(2); }
html = html.replace('<!-- PLAYABLES SDK HERE -->', noSdk ? '<!-- Playables SDK tag omitted (--no-sdk) -->' : SDK_TAG);
fs.writeFileSync(path.join(out, 'index.html'), html);

// safety net: nothing of the debug tooling may be left in the package
const files = walk(out, []), problems = [];
let bytes = 0;
for (const f of files) {
  const rel = path.relative(out, f), txt = fs.readFileSync(f, 'utf8');
  bytes += txt.length;
  if (/js[\\/]debug[\\/]/.test(rel)) problems.push(rel + ': debug file shipped');
  if (/window\.__game\s*=/.test(txt)) problems.push(rel + ': defines window.__game');
  if (/js\/debug\//.test(txt)) problems.push(rel + ': references js/debug/');
}
if (!/BUILD = 'playables'/.test(fs.readFileSync(path.join(out, 'js', 'build_flags.js'), 'utf8'))) problems.push('build flag not set');
if (problems.length) { console.error('package check FAILED:\n  ' + problems.join('\n  ')); process.exit(1); }
console.log('Playables package: ' + path.relative(root, out) + '/  ' + files.length + ' files, ' + Math.round(bytes / 1024) + ' KB' + (noSdk ? '  (no SDK tag)' : '  (SDK tag inserted)'));
console.log('zip the CONTENTS of that folder (index.html at the root of the archive).');
